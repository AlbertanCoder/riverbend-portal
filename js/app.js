/* Riverbend — shared client helpers. CSP-compliant: no inline code.
   Two deployment modes:
   - Same-origin (served by the VPS):  apiBase = ""       cookie sessions
   - GitHub Pages (static host):       apiBase = VPS URL   Bearer tokens
   The active mode is set in js/config.js (generated by scripts/build_pages.py). */
const RB = {
  apiBase: (typeof RB_CONFIG !== "undefined" && RB_CONFIG.apiBase) || "",
  csrf: { "X-Riverbend-Client": "riverbend-ui" },

  token() { return sessionStorage.getItem("rb_token") || ""; },
  setToken(t) { if (t) sessionStorage.setItem("rb_token", t); },
  clearToken() { sessionStorage.removeItem("rb_token"); },

  async api(path, options = {}) {
    const opts = Object.assign({ credentials: "include", headers: {} }, options);
    const headers = Object.assign(
      { "Content-Type": "application/json" },
      opts.headers, (opts.method && opts.method !== "GET") ? RB.csrf : {}
    );
    const tok = RB.token();
    if (tok) headers["Authorization"] = "Bearer " + tok;
    opts.headers = headers;
    const res = await fetch(RB.apiBase + path, opts);
    let body = null;
    try { body = await res.json(); } catch (e) { body = { detail: res.statusText }; }
    if (!res.ok) {
      const err = new Error(body.detail || ("Request failed (" + res.status + ")"));
      err.status = res.status;
      throw err;
    }
    return body;
  },

  money(n) {
    return (n == null ? 0 : n).toLocaleString("en-CA", {
      style: "currency", currency: "CAD", maximumFractionDigits: 2,
    });
  },

  num(n) { return (n == null ? 0 : n).toLocaleString("en-CA"); },

  esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({
      "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
    }[c]));
  },

  taxBadge(status) {
    const map = { paid: "ok", partial: "warn", outstanding: "bad" };
    return '<span class="badge badge-' + (map[status] || "info") + '">' +
      RB.esc(status) + "</span>";
  },

  /* Password strength meter (client-side heuristic; server enforces policy). */
  strength(password) {
    let score = 0;
    if (password.length >= 8) score++;
    if (password.length >= 12) score++;
    if (/[a-z]/.test(password) && /[A-Z]/.test(password)) score++;
    if (/\d/.test(password)) score++;
    if (/[^A-Za-z0-9]/.test(password)) score++;
    const labels = ["Very weak", "Weak", "Fair", "Good", "Strong", "Very strong"];
    const colors = ["#DA291C", "#DA291C", "#FEBA35", "#FEBA35", "#006F4C", "#006F4C"];
    const pct = Math.min(100, score * 20);
    return { score, pct, label: labels[score], color: colors[score] };
  },

  /* Session-aware navigation. */
  async hydrateHeader() {
    const slot = document.getElementById("nav-user");
    if (!slot) return;
    try {
      const me = await RB.api("/api/auth/me");
      const first = RB.esc(me.user.full_name.split(" ")[0]);
      slot.innerHTML =
        '<span class="strip-sub">Signed in: ' + first + "</span>" +
        (me.user.role !== "resident" ? '<a href="' + (RB.apiBase ? "admin.html" : "/admin") + '">Staff</a>' : "") +
        '<a href="' + (RB.apiBase ? "portal.html" : "/portal") + '">My account</a>' +
        '<button type="button" id="logout-btn">Sign out</button>';
      const btn = document.getElementById("logout-btn");
      if (btn) btn.addEventListener("click", async () => {
        try { await RB.api("/api/auth/logout", { method: "POST", body: "{}" }); } catch (e) {}
        RB.clearToken();
        window.location.href = RB.apiBase ? "index.html" : "/";
      });
    } catch (e) {
      slot.innerHTML = '<a href="' + (RB.apiBase ? "login.html" : "/login") + '">Sign in</a>' +
        '<a href="' + (RB.apiBase ? "login.html#register" : "/login#register") + '">Create account</a>';
    }
  },
};

document.addEventListener("DOMContentLoaded", RB.hydrateHeader);